/**
 * Turns the dumped seed dataset into SQL that populates D1.
 *
 * The point of generating this rather than hand-writing fixtures is that the
 * database ends up holding exactly what the UI rendered before a backend
 * existed — same 380 members, same 37,410 check-ins, same numbers on every
 * screen — so "did the migration change any behaviour?" has an answerable
 * answer.
 *
 * Three shapes are flattened on the way in, for the reasons given in
 * server/db/schema.ts:
 *   - member.metrics.*   -> metric_* columns
 *   - class.roster/waitlist -> class_seats rows
 *   - notification.entity   -> entity_type / entity_id
 * And three fields are dropped because they are derived, not stored:
 *   member.risk (lib/risk.ts), lead.ageDays (NOW - createdDate),
 *   company.employeeMemberIds (verified identical to members.company_id).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const data = JSON.parse(readFileSync(path.join(root, 'server/db/seed-data.json'), 'utf8'))

/** SQLite literal. Booleans become 0/1, arrays/objects become JSON text. */
function lit(v) {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'boolean') return v ? '1' : '0'
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL'
  if (typeof v === 'object') return quote(JSON.stringify(v))
  return quote(String(v))
}

function quote(s) {
  return `'${s.replace(/'/g, "''")}'`
}

const chunks = []

/**
 * Multi-row INSERTs, batched. SQLite caps a statement at 999 bound parameters,
 * but these are literals rather than binds; the batch size is about keeping any
 * single statement small enough to read and to fit D1's request limits.
 */
function insert(table, columns, rows, batchSize = 200) {
  if (!rows.length) return
  chunks.push(`-- ${table}: ${rows.length} rows`)
  for (let i = 0; i < rows.length; i += batchSize) {
    const slice = rows.slice(i, i + batchSize)
    const values = slice.map((r) => `(${columns.map((c) => lit(r[c])).join(',')})`).join(',\n  ')
    chunks.push(`INSERT INTO ${table} (${columns.join(',')}) VALUES\n  ${values};`)
  }
  chunks.push('')
}

chunks.push('-- Generated by scripts/build-seed-sql.mjs — do not edit by hand.')
chunks.push('-- Regenerate with: pnpm seed:build\n')

// --- locations -------------------------------------------------------------
