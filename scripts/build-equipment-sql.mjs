/**
 * Emits `server/db/seed-equipment.sql` — the equipment tables only.
 *
 * Deliberately separate from `seed.sql` rather than folded into it. The main
 * seed is a one-shot load of an empty database; production already holds the
 * other ten tables plus whatever has been written since (real refunds, real
 * check-ins). Regenerating and re-running the whole seed against production
 * would either collide on every primary key or, if anyone "fixed" that with
 * DELETEs, wipe live data. A file that touches only the four new tables can be
 * applied to production safely, which is the point.
 *
 *     pnpm seed:dump && pnpm equipment:build   # regenerate
 *     pnpm equipment:local | equipment:remote  # apply
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const data = JSON.parse(readFileSync(path.join(root, 'server/db/seed-data.json'), 'utf8'))

if (!data.equipment) {
  console.error('seed-data.json has no equipment — run `pnpm seed:dump` first.')
  process.exit(1)
}

function quote(s) {
  return `'${String(s).replace(/'/g, "''")}'`
}

function lit(v) {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'boolean') return v ? '1' : '0'
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL'
  if (typeof v === 'object') return quote(JSON.stringify(v))
  return quote(v)
}

const chunks = [
  '-- Generated by scripts/build-equipment-sql.mjs — do not edit by hand.',
  '-- Regenerate with: pnpm seed:dump && pnpm equipment:build',
  '-- Safe to run against a database that already holds the other tables.',
  '',
]

function insert(table, columns, rows, batchSize = 200) {
  if (!rows.length) return
  chunks.push(`-- ${table}: ${rows.length} rows`)
  for (let i = 0; i < rows.length; i += batchSize) {
    const slice = rows.slice(i, i + batchSize)
    const values = slice.map((r) => `(${columns.map((c) => lit(r[c])).join(',')})`).join(',\n  ')
    chunks.push(`INSERT INTO ${table} (${columns.join(',')}) VALUES\n  ${values};`)
  }
  chunks.push('')
}

insert(
  'equipment',
  [
    'id', 'name', 'category', 'make', 'model', 'asset_tag', 'location', 'zone',
    'quantity', 'status', 'purchase_date', 'unit_cost', 'useful_life_months',
    'service_interval_days', 'last_service_date', 'bookable', 'slot_minutes', 'notes',
  ],
  data.equipment.map((e) => ({
    ...e,
    asset_tag: e.assetTag,
    purchase_date: e.purchaseDate,
    unit_cost: e.unitCost,
    useful_life_months: e.usefulLifeMonths,
    service_interval_days: e.serviceIntervalDays,
    last_service_date: e.lastServiceDate,
    slot_minutes: e.slotMinutes,
  })),
)

insert(
  'equipment_faults',
  [
    'id', 'equipment_id', 'reported_by', 'reporter_name', 'reported_at',
    'severity', 'summary', 'status', 'resolved_at', 'resolution_note',
  ],
  data.equipmentFaults.map((f) => ({
    ...f,
    equipment_id: f.equipmentId,
    reported_by: f.reportedBy,
    reporter_name: f.reporterName,
    reported_at: f.reportedAt,
    resolved_at: f.resolvedAt,
    resolution_note: f.resolutionNote,
  })),
)

insert(
  'equipment_services',
  ['id', 'equipment_id', 'date', 'kind', 'vendor', 'cost', 'note'],
  data.equipmentServices.map((s) => ({ ...s, equipment_id: s.equipmentId })),
)

insert(
  'equipment_reservations',
  ['id', 'equipment_id', 'member_id', 'date', 'start_time', 'duration_min', 'status', 'created_at'],
  data.equipmentReservations.map((r) => ({
    ...r,
    equipment_id: r.equipmentId,
    member_id: r.memberId,
    start_time: r.startTime,
    duration_min: r.durationMin,
    created_at: r.createdAt,
  })),
  300,
)

const sql = chunks.join('\n')
const dest = path.join(root, 'server/db/seed-equipment.sql')
writeFileSync(dest, sql)

console.log(`wrote ${dest}`)
console.log(`  equipment              ${data.equipment.length}`)
console.log(`  equipment_faults       ${data.equipmentFaults.length}`)
console.log(`  equipment_services     ${data.equipmentServices.length}`)
console.log(`  equipment_reservations ${data.equipmentReservations.length}`)
console.log(`  ${(sql.length / 1024).toFixed(0)} KB`)
