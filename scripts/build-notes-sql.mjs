/**
 * Emits `server/db/seed-notes.sql` — the `member_notes` table only.
 *
 * Same reasoning as `build-equipment-sql.mjs`: production already holds ten
 * tables plus everything written since, so the seed that moves the notes into
 * the database has to touch nothing else.
 *
 * These notes were generated on the client and rendered on the profile screen
 * long before they had a table. Seeding exactly what the generator produces is
 * what makes the switch invisible — the notes tab shows the same history after
 * it starts reading from D1 as it did before.
 *
 *     pnpm seed:dump && pnpm notes:build   # regenerate
 *     pnpm notes:local | notes:remote      # apply
 */
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const data = JSON.parse(readFileSync(path.join(root, 'server/db/seed-data.json'), 'utf8'))

if (!data.memberNotes) {
  console.error('seed-data.json has no memberNotes — run `pnpm seed:dump` first.')
  process.exit(1)
}

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`
const lit = (v) => {
  if (v === null || v === undefined) return 'NULL'
  if (typeof v === 'boolean') return v ? '1' : '0'
  if (typeof v === 'number') return Number.isFinite(v) ? String(v) : 'NULL'
  return quote(v)
}

const columns = ['id', 'member_id', 'kind', 'body', 'author_id', 'timestamp', 'pinned']
const rows = data.memberNotes.map((n) => ({
  id: n.id,
  member_id: n.memberId,
  kind: n.kind,
  body: n.body,
  author_id: n.authorId,
  timestamp: n.timestamp,
  pinned: n.pinned,
}))

const chunks = [
  '-- Generated by scripts/build-notes-sql.mjs — do not edit by hand.',
  '-- Regenerate with: pnpm seed:dump && pnpm notes:build',
  '-- Safe to run against a database that already holds the other tables.',
  '',
  `-- member_notes: ${rows.length} rows`,
]

for (let i = 0; i < rows.length; i += 300) {
  const slice = rows.slice(i, i + 300)
  const values = slice.map((r) => `(${columns.map((c) => lit(r[c])).join(',')})`).join(',\n  ')
  chunks.push(`INSERT INTO member_notes (${columns.join(',')}) VALUES\n  ${values};`)
}

const sql = chunks.join('\n') + '\n'
const dest = path.join(root, 'server/db/seed-notes.sql')
writeFileSync(dest, sql)

console.log(`wrote ${dest}`)
console.log(`  member_notes ${rows.length} rows`)
console.log(`  ${(sql.length / 1024).toFixed(0)} KB`)
